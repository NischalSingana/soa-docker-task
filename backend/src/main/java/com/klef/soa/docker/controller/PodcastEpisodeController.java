package com.klef.soa.docker.controller;


import java.util.HashMap;
import java.util.List;
import java.util.Map;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;

import org.springframework.web.bind.annotation.RestController;

import com.klef.soa.docker.dto.PodcastEpisodeRequestDTO;
import com.klef.soa.docker.dto.PodcastEpisodeResponseDTO;
import com.klef.soa.docker.service.PodcastEpisodeService;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;

@RestController
@CrossOrigin(origins = "*")
@Tag(name = "Podcast Episodes", description = "Endpoints for managing podcast episode records")
public class PodcastEpisodeController {

    private final PodcastEpisodeService service;

    public PodcastEpisodeController(PodcastEpisodeService service) {
        this.service = service;
    }

    @GetMapping("/")
    @Operation(summary = "Home / Health check", description = "Verifies the backend service is up and running")
    public ResponseEntity<Map<String, Object>> home() {
        Map<String, Object> status = new HashMap<>();
        status.put("service", "Podcast Episode Management API");
        status.put("studentId", "2400030188");
        status.put("status", "UP");
        return ResponseEntity.ok(status);
    }

    @PostMapping("/Add")
    @Operation(summary = "Add a new podcast episode", description = "Creates a new podcast episode record. ID is automatically generated by the database.")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "201", description = "Episode created successfully"),
            @ApiResponse(responseCode = "400", description = "Validation failed for input data")
    })
    public ResponseEntity<?> addEpisode(@Valid @RequestBody PodcastEpisodeRequestDTO request) {
        PodcastEpisodeResponseDTO created = service.addEpisode(request);

        Map<String, Object> response = new HashMap<>();
        response.put("message", "Podcast Episode Added Successfully. ID: " + created.getId());
        response.put("episode", created);
        return ResponseEntity.status(HttpStatus.CREATED).body(response);
    }

    @GetMapping("/DisplayAll")
    @Operation(summary = "Display all podcast episodes", description = "Fetches all saved podcast episodes")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "200", description = "Successfully retrieved records (an empty array is returned when no records exist)")
    })
    public ResponseEntity<List<PodcastEpisodeResponseDTO>> displayAllEpisodes() {
        List<PodcastEpisodeResponseDTO> episodes = service.displayAllEpisodes();
        return ResponseEntity.ok(episodes);
    }

    @GetMapping("/Get/{id}")
    @Operation(summary = "Get podcast episode by ID", description = "Retrieves a single episode record by its ID")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "200", description = "Episode retrieved successfully"),
            @ApiResponse(responseCode = "404", description = "Episode not found")
    })
    public ResponseEntity<?> getEpisodeById(@PathVariable Long id) {
        PodcastEpisodeResponseDTO episode = service.getEpisodeById(id);
        if (episode != null) {
            return ResponseEntity.ok(episode);
        } else {
            return ResponseEntity.status(HttpStatus.NOT_FOUND).body("Podcast Episode Not Found");
        }
    }

    @PutMapping("/Update/{id}")
    @Operation(summary = "Update podcast episode by ID", description = "Updates fields of an existing episode record")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "200", description = "Episode updated successfully"),
            @ApiResponse(responseCode = "400", description = "Validation failed for update request"),
            @ApiResponse(responseCode = "404", description = "Episode not found")
    })
    public ResponseEntity<?> updateEpisode(@PathVariable Long id, @Valid @RequestBody PodcastEpisodeRequestDTO request) {
        PodcastEpisodeResponseDTO updated = service.updateEpisode(id, request);
        if (updated != null) {
            Map<String, Object> response = new HashMap<>();
            response.put("message", "Podcast Episode Updated Successfully. ID: " + updated.getId());
            response.put("episode", updated);
            return ResponseEntity.ok(response);
        } else {
            return ResponseEntity.status(HttpStatus.NOT_FOUND).body("Podcast Episode Not Found");
        }
    }

    @DeleteMapping("/Delete/{id}")
    @Operation(summary = "Delete podcast episode by ID", description = "Deletes an existing episode record by its primary key ID")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "200", description = "Episode deleted successfully"),
            @ApiResponse(responseCode = "404", description = "Episode not found")
    })
    public ResponseEntity<String> deleteEpisode(@PathVariable Long id) {
        boolean deleted = service.deleteEpisode(id);
        if (deleted) {
            return ResponseEntity.ok("Podcast Episode Deleted Successfully");
        } else {
            return ResponseEntity.status(HttpStatus.NOT_FOUND).body("Podcast Episode Not Found");
        }
    }
}
